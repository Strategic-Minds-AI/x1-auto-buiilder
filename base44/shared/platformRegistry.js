export function getPlatformById(id) {
  return PLATFORM_PACKS.find((p) => p.stable_id === id);
}

export function getPlatformsByCategory(category) {
  return PLATFORM_PACKS.filter((p) => p.category === category);
}

export function getPlatformsForIndustry(familyId) {
  return PLATFORM_PACKS.filter(
    (p) => p.recommended_industries.includes(familyId) || p.recommended_industries.includes("all")
  );
}

