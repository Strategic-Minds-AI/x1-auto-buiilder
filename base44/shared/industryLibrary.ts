export function generateUseCases(): any[] {
  const useCases: any[] = [];
  for (let i = 0; i < INDUSTRIES.length; i++) {
    const industry = INDUSTRIES[i];
    const subs = SUBINDUSTRIES[industry];
    const scores = SCORE_PATTERNS[industry];
    for (let j = 0; j < subs.length; j++) {
      const subindustry = subs[j];
      for (let k = 0; k < ARCHETYPES.length; k++) {
        const archetype = ARCHETYPES[k];
        const id = `X1-${String(i + 1).padStart(2, "0")}-${String(j + 1).padStart(2, "0")}-${String(k + 1).padStart(2, "0")}`;
        const opportunityScore = Math.round(
          (scores.autonomy * scores.monetization * scores.repeatability) / scores.complexity * 4
        );
        useCases.push({
          use_case_id: id,
          industry,
          subindustry,
          system_archetype: archetype.name,
          system_idea: `${subindustry} — ${archetype.name}`,
          core_outcome: `Build a production-oriented ${subindustry.toLowerCase()} system that ${archetype.name.toLowerCase()}. X1 provides the control plane, validation, and autonomous execution.`,
          frontend_surfaces: archetype.frontend,
          backend_components: archetype.backend,
          agents_ai: archetype.agents,
          key_connectors: archetype.connectors,
          autonomy_score: scores.autonomy,
          monetization_score: scores.monetization,
          complexity_score: scores.complexity,
          repeatability_score: scores.repeatability,
          monetization_model: archetype.monetization_model,
          setup_price: archetype.setup_price,
          monthly_price: archetype.monthly_price,
          risk_class: scores.risk,
          protected_gates: archetype.protected_gates,
          recommended_stack: archetype.stack,
          opportunity_score: opportunityScore,
          status: "available",
        });
      }
    }
  }
  return useCases;
}